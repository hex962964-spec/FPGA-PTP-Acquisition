`timescale 1ns / 1ps
`default_nettype none
//////////////////////////////////////////////////////////////////////////////////
// Module: observer_top_phy
// -----------------------------------------------------------------------------
// Purpose:
//   Board/L1-L2 boundary for the Observer FPGA foundation.
//
// Responsibilities:
//   1) RGMII TX: internal MAC bytes -> GMII -> Xilinx ODDR RGMII.
//   2) RGMII RX: Xilinx IDDR RGMII -> GMII -> MAC bytes.
//   3) MAC TX: insert preamble/SFD/FCS/padding/IFG.
//   4) MAC RX: strip preamble/FCS and timestamp frame start.
//
// Clocking:
//   - tx_clk      = 125 MHz eth_tx_clk
//   - tx_clk_90   = 125 MHz eth_tx_clk_90, used for RGMII TXC
//   - rx_clk_90   = 125 MHz shifted RX clock generated by clk_eth_rx
//////////////////////////////////////////////////////////////////////////////////
module observer_top_phy #(
    parameter SIMULATION = 1'b0
)(
    input  wire        tx_clk,
    input  wire        tx_clk_90,
    input  wire        tx_rst_n,

    input  wire        rx_clk_90,
    input  wire        rx_rst_n,

    input  wire        tx_enable,
    input  wire        rx_enable,

    input  wire [63:0] tx_tod_time_ns,
    input  wire [47:0] tx_tod_seconds,
    input  wire [31:0] tx_tod_nanoseconds,
    input  wire        tx_tod_time_valid,
    input  wire [63:0] rx_tod_time_ns,
    input  wire [47:0] rx_tod_seconds,
    input  wire [31:0] rx_tod_nanoseconds,
    input  wire        rx_tod_time_valid,

    // MAC-side TX input, frame body only, no preamble/FCS.
    input  wire [7:0]  s_axis_tx_tdata,
    input  wire        s_axis_tx_tvalid,
    input  wire        s_axis_tx_tlast,
    output wire        s_axis_tx_tready,
    input  wire [3:0]  s_axis_tx_tuser,

    // MAC-side RX output, frame body only, no preamble/FCS.
    output wire [7:0]  m_axis_rx_tdata,
    output wire        m_axis_rx_tvalid,
    output wire        m_axis_rx_tlast,
    output wire [63:0] m_axis_rx_timestamp_ns,
    output wire [47:0] m_axis_rx_timestamp_seconds,
    output wire [31:0] m_axis_rx_timestamp_nanoseconds,
    output wire        m_axis_rx_timestamp_valid,

    // Optional TX timestamp sideband for future PTP event frames.
    output wire [63:0] tx_timestamp_ns,
    output wire [47:0] tx_timestamp_seconds,
    output wire [31:0] tx_timestamp_nanoseconds,
    output wire        tx_timestamp_valid,

    // RGMII pins.
    output wire        rgmii_txc,
    output wire [3:0]  rgmii_txd,
    output wire        rgmii_tx_ctl,
    input  wire [3:0]  rgmii_rxd,
    input  wire        rgmii_rx_ctl,

    // Statistics.
    output wire        tx_busy,
    output wire        rx_busy,
    output wire [31:0] tx_frame_count,
    output wire [31:0] tx_byte_count,
    output wire [15:0] tx_last_error,
    output wire [31:0] rx_frame_count,
    output wire [31:0] rx_drop_count,
    output wire [15:0] rx_last_error
);

    wire [7:0] gmii_txd_w;
    wire       gmii_tx_en_w;
    wire       gmii_tx_er_w;

    wire [7:0] gmii_rxd_w;
    wire       gmii_rx_dv_w;
    wire       gmii_rx_er_w;

    observer_axis_mac_tx u_mac_tx (
        .clk                  (tx_clk),
        .rst_n                (tx_rst_n),
        .tx_enable            (tx_enable),
        .s_axis_tdata         (s_axis_tx_tdata),
        .s_axis_tvalid        (s_axis_tx_tvalid),
        .s_axis_tlast         (s_axis_tx_tlast),
        .s_axis_tready        (s_axis_tx_tready),
        .s_axis_tuser         (s_axis_tx_tuser),
        .ptp_tod_time_ns      (tx_tod_time_ns),
        .ptp_tod_seconds      (tx_tod_seconds),
        .ptp_tod_nanoseconds  (tx_tod_nanoseconds),
        .ptp_tod_time_valid   (tx_tod_time_valid),
        .gmii_txd             (gmii_txd_w),
        .gmii_tx_en           (gmii_tx_en_w),
        .gmii_tx_er           (gmii_tx_er_w),
        .ptp_txstamp_ns          (tx_timestamp_ns),
        .ptp_txstamp_seconds     (tx_timestamp_seconds),
        .ptp_txstamp_nanoseconds (tx_timestamp_nanoseconds),
        .ptp_txstamp_valid       (tx_timestamp_valid),
        .tx_busy              (tx_busy),
        .stat_frame_count     (tx_frame_count),
        .stat_mac_byte_count  (tx_byte_count),
        .stat_last_error      (tx_last_error)
    );

    observer_rgmii_tx_if #(
        .SIMULATION(SIMULATION)
    ) u_rgmii_tx_if (
        .clk          (tx_clk),
        .clk_90       (tx_clk_90),
        .rst_n        (tx_rst_n),
        .gmii_txd     (gmii_txd_w),
        .gmii_tx_en   (gmii_tx_en_w),
        .gmii_tx_er   (gmii_tx_er_w),
        .rgmii_txc    (rgmii_txc),
        .rgmii_txd    (rgmii_txd),
        .rgmii_tx_ctl (rgmii_tx_ctl)
    );

    observer_rgmii_rx_if #(
        .SIMULATION(SIMULATION)
    ) u_rgmii_rx_if (
        .clk_90       (rx_clk_90),
        .rst_n        (rx_rst_n),
        .rgmii_rxd    (rgmii_rxd),
        .rgmii_rx_ctl (rgmii_rx_ctl),
        .gmii_rxd     (gmii_rxd_w),
        .gmii_rx_dv   (gmii_rx_dv_w),
        .gmii_rx_er   (gmii_rx_er_w)
    );

    observer_axis_mac_rx u_mac_rx (
        .clk                  (rx_clk_90),
        .rst_n                (rx_rst_n),
        .rx_enable            (rx_enable),
        .gmii_rxd             (gmii_rxd_w),
        .gmii_rx_dv           (gmii_rx_dv_w),
        .gmii_rx_er           (gmii_rx_er_w),
        .ptp_tod_time_ns      (rx_tod_time_ns),
        .ptp_tod_seconds      (rx_tod_seconds),
        .ptp_tod_nanoseconds  (rx_tod_nanoseconds),
        .ptp_tod_time_valid   (rx_tod_time_valid),
        .m_axis_tdata         (m_axis_rx_tdata),
        .m_axis_tvalid        (m_axis_rx_tvalid),
        .m_axis_tlast         (m_axis_rx_tlast),
        .ptp_rxstamp_ns          (m_axis_rx_timestamp_ns),
        .ptp_rxstamp_seconds     (m_axis_rx_timestamp_seconds),
        .ptp_rxstamp_nanoseconds (m_axis_rx_timestamp_nanoseconds),
        .ptp_rxstamp_valid       (m_axis_rx_timestamp_valid),
        .rx_busy              (rx_busy),
        .stat_frame_count     (rx_frame_count),
        .stat_drop_count      (rx_drop_count),
        .stat_last_error      (rx_last_error)
    );

endmodule
`default_nettype wire
